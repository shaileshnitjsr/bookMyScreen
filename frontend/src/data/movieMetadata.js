export function buildMovieRows(movies = []) {
  if (!movies || movies.length === 0) return [];

  const trendingTitles = ["Dune: Part Two", "Oppenheimer", "Top Gun: Maverick", "Spider-Man: Across the Spider-Verse", "Interstellar"];
  const actionTitles = ["Top Gun: Maverick", "The Dark Knight", "The Batman", "Avengers: Endgame", "Inception"];
  const sciFiTitles = ["Interstellar", "Inception", "Dune: Part Two", "Avatar: The Way of Water", "Spider-Man: Across the Spider-Verse"];
  const criticallyAcclaimedTitles = ["The Dark Knight", "Oppenheimer", "Inception", "Interstellar", "Dune: Part Two"];

  const getMoviesByTitles = (titles) => {
    return titles
      .map((t) => movies.find((m) => m.title.toLowerCase() === t.toLowerCase()))
      .filter(Boolean);
  };

  const rows = [
    {
      id: "trending-now",
      title: "Trending Now in Theatres",
      movies: getMoviesByTitles(trendingTitles),
    },
    {
      id: "blockbusters-action",
      title: "Blockbuster Action & Thrills",
      movies: getMoviesByTitles(actionTitles),
    },
    {
      id: "scifi-mindbenders",
      title: "Mind-Bending Sci-Fi & Epics",
      movies: getMoviesByTitles(sciFiTitles),
    },
    {
      id: "critically-acclaimed",
      title: "Critically Acclaimed Masterpieces",
      movies: getMoviesByTitles(criticallyAcclaimedTitles),
    },
    {
      id: "all-movies",
      title: "Explore the Complete CineFlow Collection",
      movies: movies,
    },
  ];

  return rows.filter((r) => r.movies.length > 0);
}
